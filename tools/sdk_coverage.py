#!/usr/bin/env python3
"""SDK coverage: our operation count vs the official Python SDK method count.

For every installed huaweicloudsdk* package, counts the client's public
API methods and compares with the operations Larrot serves for the
mapped services. This is an honest coverage signal (the Moto
IMPLEMENTATION_COVERAGE pattern): the SDK method count approximates the
real API surface per service.

Writes SDK_COVERAGE.md. Enforced by tests/test_sdk_coverage_doc.py when
the SDKs are installed (pip install larrot[sdk]).
"""

import os
import re
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))

from collections import defaultdict  # noqa: E402

from fastapi.testclient import TestClient  # noqa: E402

from larrot.app import create_app  # noqa: E402

OUT = os.path.join(os.path.dirname(__file__), "..", "SDK_COVERAGE.md")

# SDK package -> how to count Larrot's corresponding operations:
# tags: service tags in the OpenAPI spec; paths: substrings to match
# instead (for services whose routes live in another service's router).
MAPPING = {
    "huaweicloudsdkecs": {"tags": ["ECS", "ECS Extras", "ECS Batch", "ECS Keypairs", "ECS Server Groups"]},
    "huaweicloudsdkvpc": {"tags": ["VPC", "VPC Peering", "VPC Routes", "Network ACL"]},
    "huaweicloudsdkevs": {"tags": ["EVS"]},
    "huaweicloudsdkims": {"tags": ["IMS"]},
    "huaweicloudsdkeip": {"paths": ["publicips", "bandwidths"]},
    "huaweicloudsdkiam": {"tags": ["IAM"]},
}

METHOD_RE = re.compile(r"^[a-z][a-z0-9_]*$")


def sdk_method_count(package: str) -> int | None:
    """Public API methods on the service client (no _private/_invoker)."""
    try:
        if package == "huaweicloudsdkecs":
            from huaweicloudsdkecs.v2 import EcsClient as C
        elif package == "huaweicloudsdkvpc":
            from huaweicloudsdkvpc.v2 import VpcClient as C
        elif package == "huaweicloudsdkevs":
            from huaweicloudsdkevs.v2 import EvsClient as C
        elif package == "huaweicloudsdkims":
            from huaweicloudsdkims.v2 import ImsClient as C
        elif package == "huaweicloudsdkeip":
            from huaweicloudsdkeip.v2 import EipClient as C
        elif package == "huaweicloudsdkiam":
            from huaweicloudsdkiam.v3 import IamClient as C
        else:
            return None
    except ImportError:
        return None
    count = 0
    for name in dir(C):
        if name.startswith("_") or name.endswith(("_invoker", "_http_info")):
            continue
        fn = getattr(C, name, None)
        if callable(fn) and METHOD_RE.match(name):
            count += 1
    return count


def our_op_counts() -> dict:
    """Per service tag AND per path substring: operation counts."""
    client = TestClient(create_app())
    spec = client.get("/openapi.json").json()
    by_tag = defaultdict(int)
    by_path = defaultdict(int)
    for path, methods in spec["paths"].items():
        n = sum(1 for m in methods
                if m in ("get", "post", "put", "delete", "patch", "head"))
        if not n:
            continue
        for m, op in methods.items():
            if m in ("get", "post", "put", "delete", "patch", "head"):
                for tag in op.get("tags", ["untagged"]):
                    by_tag[tag] += 1
        for needle in ("publicips", "bandwidths"):
            if needle in path:
                by_path[needle] += n
    return {"tags": by_tag, "paths": by_path}


def _our_count(ours: dict, spec: dict) -> int:
    return (sum(ours["tags"].get(t, 0) for t in spec.get("tags", []))
            + sum(ours["paths"].get(p, 0) for p in spec.get("paths", [])))


def generate() -> str:
    ours = our_op_counts()
    lines = [
        "# SDK coverage",
        "",
        "Larrot's operation count per service vs the official Huawei Cloud",
        "Python SDK's method count (an approximation of the real API surface).",
        "Generated by `tools/sdk_coverage.py`; enforced by a test when the",
        "SDKs are installed (`pip install larrot[sdk]`).",
        "",
        "| SDK package | SDK methods | Larrot operations | Coverage |",
        "|---|---:|---:|---:|",
    ]
    for package, spec in MAPPING.items():
        sdk_n = sdk_method_count(package)
        our_n = _our_count(ours, spec)
        if sdk_n is None:
            lines.append(f"| {package} | (not installed) | {our_n} | - |")
        else:
            pct = round(100 * our_n / sdk_n) if sdk_n else 0
            lines.append(f"| {package} | {sdk_n} | {our_n} | {min(pct, 100)}% |")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    content = generate()
    with open(OUT, "w") as f:
        f.write(content)
    print(f"wrote {os.path.normpath(OUT)}")
